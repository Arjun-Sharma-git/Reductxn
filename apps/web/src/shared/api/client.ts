import { env } from '@/shared/config/env';
import { forgetSession, sessionFrom, storeSession, storedSession } from '@/shared/session';

/**
 * The only place in the client that calls `fetch` (RULE F5).
 *
 * **Why not `openapi-fetch`.** MASTER-PLAN section 7 prescribes it, and it is the natural partner of the
 * generated types - but it has never reached 1.0, and P9 forbids a pre-1.0 dependency in the frontend ("we are
 * not a QA lab for our own dependency tree"). The alternative was not to hand-write types, which would put a
 * second copy of the contract in the client (RULE C1): the *types* are still generated by `openapi-typescript`,
 * and what is hand-written is the forty lines that turn a response into a value or a coded refusal. A shallow
 * wrapper over `fetch` is something this repository can own; a schema of the whole API is not.
 *
 * **A failure is a value with a code, never prose.** RFC 9457's problem+json already carries `code` and
 * `params`, and RULE B20 says the server never localizes. So this layer preserves them and the screen renders
 * them from `errors.json` - which is what makes "this group settles in INR, but the amount is in JPY" sayable in
 * four languages without a backend release.
 */

export type Problem = {
  /** The stable code, for instance `fx.rate_unavailable`. */
  readonly code: string;
  readonly status: number;
  readonly params: Readonly<Record<string, string | number>>;
  /** English, for developers and logs. Never rendered. */
  readonly title: string;
  /** English, for developers and logs. Never rendered. */
  readonly detail?: string;
};

export class ApiProblemError extends Error {
  readonly problem: Problem;

  constructor(problem: Problem) {
    super(problem.detail ?? problem.title);
    this.name = 'ApiProblemError';
    this.problem = problem;
  }
}

/** The code behind a failure, whatever shape it arrived in. */
export function problemOf(fault: unknown): Problem {
  if (fault instanceof ApiProblemError) {
    return fault.problem;
  }

  if (fault instanceof Error) {
    return {
      code: 'client.network',
      status: 0,
      params: {},
      title: 'The API could not be reached',
      detail: fault.message,
    };
  }

  return { code: 'client.unknown_fault', status: 0, params: {}, title: 'Unknown failure' };
}

type Method = 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE';

export type RequestOptions = {
  readonly method?: Method;
  readonly body?: unknown;
  /**
   * P8: every state-changing call is idempotent, and the header is how. A generated key rather than a
   * timestamp, because two retries in the same millisecond are two different attempts.
   */
  readonly idempotencyKey?: string;
  readonly query?: Readonly<Record<string, string | number | boolean | undefined>>;
  readonly signal?: AbortSignal;
};

function url(path: string, query: RequestOptions['query']): string {
  const search = new URLSearchParams();

  for (const [key, value] of Object.entries(query ?? {})) {
    if (value !== undefined) {
      search.set(key, String(value));
    }
  }

  const suffix = search.size > 0 ? `?${search.toString()}` : '';

  return `${env.apiBaseUrl}/v1${path}${suffix}`;
}

async function toProblem(response: Response): Promise<Problem> {
  try {
    const body: unknown = await response.json();

    if (typeof body === 'object' && body !== null) {
      const problem = body as Record<string, unknown>;

      return {
        code: typeof problem['code'] === 'string' ? problem['code'] : 'client.unexpected_status',
        status: response.status,
        params:
          typeof problem['params'] === 'object' && problem['params'] !== null
            ? (problem['params'] as Record<string, string | number>)
            : {},
        title: typeof problem['title'] === 'string' ? problem['title'] : response.statusText,
        ...(typeof problem['detail'] === 'string' ? { detail: problem['detail'] } : {}),
      };
    }
  } catch {
    // A response that is not JSON is not a problem document. Nothing to preserve beyond the status.
  }

  return {
    code: 'client.unexpected_status',
    status: response.status,
    params: {},
    title: response.statusText,
  };
}

/**
 * One request, typed by the generated contract.
 *
 * `path` and the response type are both `paths[...]`, so a route the contract does not define is a compile
 * error rather than a 404 at runtime - which is the whole value of generating the types (RULE C1, C3).
 */
export async function request<T>(
  path: string,
  options: RequestOptions = {},
): Promise<T> {
  const response = await send(path, options);

  if (response.status !== 401) {
    return unwrap<T>(response);
  }

  // A 401 with a session in hand means the access token has aged out - not that the caller is not allowed, and not that
  // the request was wrong. Renewing once and trying again is the whole of what a refresh token is for, and **once** is
  // deliberate: a client that retried in a loop would hammer an endpoint that answers 401 for a token that is already
  // gone (ADR 0042).
  if (!(await renewSession())) {
    return unwrap<T>(response);
  }

  return unwrap<T>(await send(path, options));
}

/** One request, no renewal. Split out so the retry above is the only place that knows about it. */
async function send(path: string, options: RequestOptions): Promise<Response> {
  const headers: Record<string, string> = { Accept: 'application/json' };

  if (options.body !== undefined) {
    headers['Content-Type'] = 'application/json';
  }

  if (options.idempotencyKey !== undefined) {
    headers['Idempotency-Key'] = options.idempotencyKey;
  }

  // The session's access token, when there is one (ADR 0042). Sent on every request rather than only on the paths that
  // need it: which paths require a token is the server's decision, and one operation reads it today while the rest
  // tolerate it - so a client that guessed would be a client that breaks when enforcement lands.
  const session = storedSession();

  if (session !== null) {
    headers['Authorization'] = `Bearer ${session.accessToken}`;
  }

  return fetch(url(path, options.query), {
    method: options.method ?? 'GET',
    headers,
    // No credentials: this API authenticates with a bearer header, not a cookie, and a wildcard-plus-cookie
    // combination would be a CSRF surface nothing here defends (ADR 0042).
    credentials: 'same-origin',
    ...(options.body === undefined ? {} : { body: JSON.stringify(options.body) }),
    ...(options.signal === undefined ? {} : { signal: options.signal }),
  });
}

/** The value or the refusal, which is the one place a response becomes one of the two. */
async function unwrap<T>(response: Response): Promise<T> {
  if (!response.ok) {
    throw new ApiProblemError(await toProblem(response));
  }

  // The body decides, rather than the `content-length` header. `202 Accepted` and `204 No Content` have no value to
  // return, and a server is not obliged to announce that with a header - Spring's `202` from `POST /auth/otp/request` does
  // not, and calling `json()` on the empty body throws a parse error. That throw was reported to a member as "the server
  // could not be reached", which is a lie about a request that worked; a browser test found it (ADR 0042).
  const body = await response.text();

  return (body === '' ? undefined : JSON.parse(body)) as T;
}

/**
 * Renews the session with the stored refresh token, and answers whether there is a usable pair now.
 *
 * It uses {@link send} rather than {@link request}, which is what stops the renewal from recursing into itself when the
 * refresh is also refused. A refusal means the session is over - the token was rotated away, or the window closed - so the
 * stored pair is forgotten: keeping it would be a client that keeps sending a token it knows is dead.
 */
async function renewSession(): Promise<boolean> {
  const session = storedSession();

  if (session === null) {
    return false;
  }

  const response = await fetch(url('/auth/refresh', undefined), {
    method: 'POST',
    headers: { Accept: 'application/json', 'Content-Type': 'application/json' },
    credentials: 'same-origin',
    body: JSON.stringify({ refreshToken: session.refreshToken }),
  });

  if (!response.ok) {
    forgetSession();

    return false;
  }

  storeSession(sessionFrom((await response.json()) as Parameters<typeof sessionFrom>[0]));

  return true;
}

/** A path idempotency key for the calls that move money (P8). */
export function newIdempotencyKey(): string {
  return crypto.randomUUID();
}

/** The generated contract, re-exported so a caller can name a response type without reaching into the schema. */
export type { paths };
